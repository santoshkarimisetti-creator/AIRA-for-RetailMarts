import React, { useState, useEffect } from 'react'
import { useNavigate } from 'react-router-dom'
import { fetchAIInsights } from '../services/api'
import { 
  Sparkles, 
  AlertTriangle, 
  TrendingUp, 
  ArrowRight, 
  ShieldCheck, 
  RefreshCw,
  PackageCheck,
  Zap,
  DollarSign
} from 'lucide-react'

export default function AIInsights() {
  const navigate = useNavigate()
  const [insights, setInsights] = useState([])
  const [isLoading, setIsLoading] = useState(true)
  const [criticalCount, setCriticalCount] = useState(0)

  const loadInsights = async () => {
    setIsLoading(true)
    try {
      const data = await fetchAIInsights()
      if (data && data.insights && data.insights.length > 0) {
        setInsights(data.insights)
        setCriticalCount(data.criticalCount || 0)
      } else {
        setInsights([])
      }
    } catch (err) {
      console.error('Failed to load AI insights:', err)
      setInsights([])
    } finally {
      setIsLoading(false)
    }
  }

  useEffect(() => {
    loadInsights()
  }, [])

  return (
    <div className="space-y-6 animate-fade-in pb-24 dashboard-workspace-bg">
      {/* Header Banner */}
      <div className="flex flex-col sm:flex-row justify-between items-start sm:items-center gap-4">
        <div>
          <h1 className="text-2xl font-bold text-slate-900 tracking-tight flex items-center space-x-2">
            <span>AIRA Autonomous Insights</span>
            <span className="px-2.5 py-0.5 rounded-full text-[10px] font-mono aira-gradient-bg text-white">
              LIVE TELEMETRY
            </span>
          </h1>
          <p className="text-xs text-slate-500">
            Real-time business recommendations generated by continuous monitoring of live store inventory, demand velocity, and margins.
          </p>
        </div>

        <button 
          onClick={loadInsights}
          disabled={isLoading}
          className="px-3.5 py-2 rounded-xl bg-white border border-slate-200 text-slate-700 hover:bg-slate-50 text-xs font-semibold flex items-center space-x-2 shadow-xs transition-colors shrink-0"
        >
          <RefreshCw className={`w-3.5 h-3.5 ${isLoading ? 'animate-spin text-blue-600' : 'text-slate-500'}`} />
          <span>Refresh Insights</span>
        </button>
      </div>

      {/* Summary KPI Strip */}
      <div className="grid grid-cols-1 sm:grid-cols-3 gap-3">
        <div className="p-4 rounded-2xl card-light flex items-center space-x-3.5">
          <div className="w-10 h-10 rounded-xl bg-blue-50 text-blue-600 flex items-center justify-center shrink-0">
            <Sparkles className="w-5 h-5" />
          </div>
          <div>
            <div className="text-xs text-slate-500 font-medium">Active Recommendations</div>
            <div className="text-lg font-black text-slate-900">{insights.length} Insights</div>
          </div>
        </div>

        <div className="p-4 rounded-2xl card-light flex items-center space-x-3.5">
          <div className="w-10 h-10 rounded-xl bg-rose-50 text-rose-600 flex items-center justify-center shrink-0">
            <AlertTriangle className="w-5 h-5" />
          </div>
          <div>
            <div className="text-xs text-slate-500 font-medium">Critical Stockout Risks</div>
            <div className="text-lg font-black text-rose-600">{criticalCount} SKUs</div>
          </div>
        </div>

        <div className="p-4 rounded-2xl card-light flex items-center space-x-3.5">
          <div className="w-10 h-10 rounded-xl bg-emerald-50 text-emerald-600 flex items-center justify-center shrink-0">
            <ShieldCheck className="w-5 h-5" />
          </div>
          <div>
            <div className="text-xs text-slate-500 font-medium">Engine Status</div>
            <div className="text-sm font-bold text-emerald-700">100% PostgreSQL Grounded</div>
          </div>
        </div>
      </div>

      {/* Insights Grid */}
      {isLoading ? (
        <div className="grid grid-cols-1 md:grid-cols-2 gap-6">
          {[1, 2, 3, 4].map(idx => (
            <div key={idx} className="p-6 rounded-2xl card-light animate-pulse space-y-4">
              <div className="h-5 bg-slate-200 rounded w-1/3"></div>
              <div className="h-14 bg-slate-100 rounded w-full"></div>
              <div className="h-9 bg-slate-200 rounded w-full"></div>
            </div>
          ))}
        </div>
      ) : insights.length === 0 ? (
        <div className="p-12 text-center card-light space-y-3">
          <PackageCheck className="w-12 h-12 text-emerald-500 mx-auto" />
          <h3 className="text-base font-bold text-slate-900">Inventory Levels Fully Optimal</h3>
          <p className="text-xs text-slate-500 max-w-md mx-auto">
            AIRA has not detected any urgent stockouts or overstocked items. All products are maintaining healthy inventory thresholds.
          </p>
        </div>
      ) : (
        <div className="grid grid-cols-1 md:grid-cols-2 gap-6">
          {insights.map((insight) => {
            const isCritical = insight.type === 'critical'
            const isOpp = insight.type === 'opportunity'
            const isWarn = insight.type === 'warning'

            return (
              <div 
                key={insight.id} 
                className={`p-6 rounded-2xl card-light flex flex-col justify-between space-y-4 hover:border-blue-400 transition-all border ${
                  isCritical ? 'hover:shadow-rose-500/5' : isOpp ? 'hover:shadow-emerald-500/5' : 'hover:shadow-amber-500/5'
                }`}
              >
                <div className="space-y-3">
                  <div className="flex items-center justify-between">
                    <span className={`px-2.5 py-1 rounded-full text-xs font-bold flex items-center space-x-1.5 ${
                      isCritical ? 'bg-rose-100 text-rose-700' :
                      isOpp ? 'bg-emerald-100 text-emerald-700' :
                      isWarn ? 'bg-amber-100 text-amber-700' :
                      'bg-blue-100 text-blue-700'
                    }`}>
                      {isCritical && <AlertTriangle className="w-3 h-3 shrink-0" />}
                      {isOpp && <TrendingUp className="w-3 h-3 shrink-0" />}
                      <span>{insight.title}</span>
                    </span>

                    {insight.metric && (
                      <span className="text-[11px] font-mono font-bold text-slate-600 bg-slate-100 px-2 py-0.5 rounded-md">
                        {insight.metric}
                      </span>
                    )}
                  </div>

                  <p className="text-sm text-slate-800 leading-relaxed font-medium">
                    {insight.message}
                  </p>
                </div>

                <button 
                  onClick={() => {
                    if (insight.actionUrl) {
                      navigate(insight.actionUrl)
                    } else {
                      navigate('/app/inventory')
                    }
                  }}
                  className={`w-full py-2.5 rounded-xl text-xs font-bold flex items-center justify-center space-x-2 shadow-xs transition-transform hover:scale-[1.01] ${
                    isCritical 
                      ? 'bg-rose-600 hover:bg-rose-700 text-white' 
                      : isOpp 
                      ? 'bg-emerald-600 hover:bg-emerald-700 text-white' 
                      : 'aira-gradient-btn'
                  }`}
                >
                  <span>{insight.actionText || 'Take Action'}</span>
                  <ArrowRight className="w-4 h-4" />
                </button>
              </div>
            )
          })}
        </div>
      )}
    </div>
  )
}
